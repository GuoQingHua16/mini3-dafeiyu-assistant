"""Port licensed upstream PNG cells to Mini3 RGB565 assets and a browser preview.

Run with .venv-assets (Pillow 12.3.0). This is deterministic asset conversion;
it neither executes upstream code nor uses its Electron runtime.
"""
from pathlib import Path
import base64
import hashlib
import json
import struct
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'mini3-agent/assets/dafeiyu'
UPSTREAM = ASSETS / 'upstream'
OUTPUT = ROOT / 'mini3-firmware/apps-ui/apps/llm/presenters'
COMMIT = '7661c8b304c5400701f91da01b1a643a207331de'
W, H = 176, 144
BG = (0x10, 0x1E, 0x23)


def cell(sheet, index, columns=4, size=512):
    x, y = index % columns * size, index // columns * size
    return sheet.crop((x, y, x + size, y + size))


def main():
    expressions = Image.open(UPSTREAM / 'expressions.png').convert('RGBA')
    idle = Image.open(UPSTREAM / 'idle-front.png').convert('RGBA')
    sleep = Image.open(UPSTREAM / 'dense-sleep.png').convert('RGBA')
    assert expressions.size == (2048, 2048) and idle.size == (2048, 1024)
    poses = [
        ('IDLE', cell(idle, 0, 2, 1024)),
        ('BLINK', cell(idle, 1, 2, 1024)),
        ('LISTEN', cell(expressions, 0)),
        ('THINK', cell(expressions, 8)),
        ('SPEAK_A', cell(expressions, 3)),
        ('SPEAK_B', cell(expressions, 2)),
        ('HAPPY', cell(expressions, 7)),
        ('SAD', cell(expressions, 11)),
        ('ANGRY', cell(expressions, 10)),
        ('SURPRISE', cell(expressions, 9)),
        ('SLEEP', cell(expressions, 15)),
        ('DROWSY', cell(sleep, 7)),
        ('SIT', cell(sleep, 13)),
        ('CURL', cell(sleep, 19)),
    ]
    frames = []
    c = ['/* Generated by mini3-agent/tools/build_dafeiyu_assets.py.',
         ' * Modified assets: YunYueSama, https://github.com/YunYueSama/codex-deepseek-pet',
         ' * Full license and modification notice: mini3-agent/assets/dafeiyu/. */',
         '#include "pet_whale_assets.h"',
         '#if LV_COLOR_DEPTH != 16 || LV_COLOR_16_SWAP',
         '#error "Mini3 whale assets require native little-endian RGB565"', '#endif']
    for name, source in poses:
        # All source cells share a square reference box. Keep that box and the
        # baseline across poses; do not crop each frame to a different scale.
        image = Image.new('RGBA', (W, H), BG + (255,))
        source = source.resize((512, 512), Image.Resampling.LANCZOS)
        source = source.crop((0, 48, 512, 496)).resize((165, H), Image.Resampling.LANCZOS)
        image.alpha_composite(source, ((W - 165) // 2, 0))
        pixels = image.convert('RGB').get_flattened_data()
        words = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in pixels]
        payload = struct.pack('<' + 'H' * len(words), *words)
        assert len(payload) == W * H * 2
        # Preview the actual quantized pixel values, including the dark matte.
        preview = Image.new('RGB', (W, H))
        preview.putdata([(((v >> 11) & 31) * 255 // 31,
                          ((v >> 5) & 63) * 255 // 63, (v & 31) * 255 // 31) for v in words])
        preview.save(ASSETS / (name.lower() + '.png'))
        c.append(f'static const uint8_t whale_{name.lower()}[] LV_ATTRIBUTE_MEM_ALIGN = {{')
        c.extend('    ' + ','.join(f'0x{b:02x}' for b in payload[start:start + 24]) + ','
                 for start in range(0, len(payload), 24))
        c.append('};')
        frames.append((name, preview))
    c.append('static const lv_img_dsc_t frames[WHALE_FRAME_COUNT] = {')
    for name, _ in frames:
        c.append(f'    [WHALE_{name}] = {{.header = {{.cf = LV_IMG_CF_TRUE_COLOR, .w = {W}, .h = {H}}}, '
                 f'.data_size = {W * H * 2}, .data = whale_{name.lower()}}},')
    c.extend(['};', 'const lv_img_dsc_t *pet_whale_frame(whale_frame_t frame)', '{',
              '    return &frames[(unsigned)frame < WHALE_FRAME_COUNT ? frame : WHALE_IDLE];', '}', ''])
    (OUTPUT / 'pet_whale_assets.c').write_text('\n'.join(c), encoding='utf-8')
    (OUTPUT / 'pet_whale_assets.h').write_text('\n'.join([
        '#ifndef PET_WHALE_ASSETS_H', '#define PET_WHALE_ASSETS_H', '#include "lvgl.h"',
        'typedef enum {', *[f'    WHALE_{name},' for name, _ in frames],
        '    WHALE_FRAME_COUNT', '} whale_frame_t;',
        'const lv_img_dsc_t *pet_whale_frame(whale_frame_t frame);', '#endif', '']), encoding='utf-8')
    font = ImageFont.truetype('C:/Windows/Fonts/msyh.ttc', 16)
    small = ImageFont.truetype('C:/Windows/Fonts/msyh.ttc', 13)
    cards = []
    for title, name, caption, color in [
        ('小聆在这里', 'IDLE', '按一下，和我聊聊', '#79AEFF'),
        ('我在听 · 15s', 'LISTEN', '现在可以说话啦', '#79AEFF'),
        ('让我想想', 'THINK', '正在认真想你的问题', '#C5BAFF'),
        ('说给你听', 'SPEAK_A', '合肥多云 15~26 19:30', '#79AEFF'),
        ('开心的小聆', 'HAPPY', '按一下，和我聊聊', '#FFE59A'),
        ('陪你休息一会', 'SLEEP', '按一下就能叫醒我', '#90ABAA')]:
        card = Image.new('RGB', (240, 240), dict(frames)['IDLE'].getpixel((0, 0)))
        card.paste(dict(frames)[name], (32, 33))
        draw = ImageDraw.Draw(card)
        draw.text((16, 13), '陪伴', font=font, fill='#EAF3E9')
        draw.text((190, 13), '70%', font=small, fill='#A5B8B8')
        draw.text((120, 178), title, font=font, fill=color, anchor='mt')
        draw.text((120, 202), caption, font=font, fill='#A5B8B8', anchor='mt')
        if name == 'LISTEN':
            draw.rounded_rectangle((16, 232, 224, 235), radius=2, fill=color)
        cards.append(card)
    contact = Image.new('RGB', (240 * 3, 240 * 2), '#192B33')
    for i, card in enumerate(cards):
        contact.paste(card, (i % 3 * 240, i // 3 * 240))
    contact.save(ASSETS / 'mini3-preview.png')
    # Show the same two-tick intermediate poses used by the native UI. This
    # preview illustrates source poses, not a recording of the physical LCD.
    sequence = ['IDLE'] * 3 + ['DROWSY'] * 2 + ['SIT'] * 2 + ['CURL'] * 2 + ['SLEEP'] * 10
    sequence += ['CURL'] * 2 + ['SIT'] * 2 + ['DROWSY'] * 2 + ['IDLE'] * 5
    dict_frames = dict(frames)
    dict_frames[sequence[0]].save(ASSETS / 'sleep-transition.gif', save_all=True,
        append_images=[dict_frames[name] for name in sequence[1:]], duration=80, loop=0)
    embedded = {name: 'data:image/png;base64,' + base64.b64encode(
                    (ASSETS / (name.lower() + '.png')).read_bytes()).decode('ascii') for name, _ in frames}
    (ASSETS / 'preview.html').write_text('''<!doctype html><meta charset="utf-8">
<title>Mini3 大肥鱼界面预览</title><style>
body{background:#0c141c;color:#eaf3e9;font:16px "Microsoft YaHei",sans-serif;text-align:center;margin:36px auto;max-width:720px}
.screen{position:relative;width:240px;height:240px;margin:24px auto;background:rgb(16,28,32);overflow:hidden;border-radius:12px;box-shadow:0 12px 70px #0008;text-align:left}
.scene{position:absolute;left:16px;top:13px}.battery{position:absolute;right:14px;top:13px;color:#a5b8b8}
img{position:absolute;left:32px;top:33px;width:176px;height:144px;animation:breathe 4s ease-in-out infinite}
@keyframes breathe{50%{transform:translateY(2px)}}
#title,#caption{position:absolute;left:12px;right:12px;text-align:center;white-space:nowrap;overflow:hidden;font-size:16px}
#title{top:178px;color:#79aeff}#caption{top:202px;color:#a5b8b8}
#progress{position:absolute;left:16px;right:16px;top:232px;height:3px;background:#79aeff;display:none}
button{background:#172b3a;color:#d7e8ff;border:1px solid #38556d;border-radius:8px;padding:9px 13px;margin:4px;cursor:pointer}
button:focus{outline:2px solid #79aeff}small{display:block;color:#a5b8b8;margin:18px}a{color:#79aeff}
</style><h2>Mini3 · 大肥鱼</h2><small>240×240 电脑布局预览；实机字体与状态值以设备为准</small>
<div class="screen"><span class="scene">陪伴</span><span class="battery">70%</span>
<img id="pet" alt="大肥鱼"><div id="title"></div><div id="caption"></div><div id="progress"></div></div>
<div id="buttons"></div><small>作者：YunYueSama · 已修改为 Mini3 帧素材<br>
<a href="https://github.com/YunYueSama/codex-deepseek-pet">原项目与署名许可</a></small><script>
const images=IMAGES_PLACEHOLDER;
const states=[['待机','IDLE','小聆在这里','按一下，和我聊聊'],['聆听','LISTEN','我在听 · 15s','现在可以说话啦'],
['思考','THINK','让我想想','正在认真想你的问题'],['说话','SPEAK_A','说给你听','合肥多云 15~26 19:30'],
['开心','HAPPY','开心的小聆','按一下，和我聊聊'],['难过','SAD','难过的小聆','按一下，和我聊聊'],
['生气','ANGRY','生气的小聆','按一下，和我聊聊'],['休息','SLEEP','陪你休息一会','按一下就能叫醒我'],
['离线','SLEEP','等你连接','请打开电脑端服务']];
let current=0,frame=0;function show(i){current=i;const s=states[i];document.getElementById('pet').src=images[s[1]];
document.getElementById('title').textContent=s[2];document.getElementById('caption').textContent=s[3];
document.getElementById('progress').style.display=i===1?'block':'none'}
states.forEach((s,i)=>{const b=document.createElement('button');b.textContent=s[0];b.onclick=()=>show(i);document.getElementById('buttons').append(b)});
setInterval(()=>{frame++;let key=states[current][1];if(current===0&&frame%32===0)key='BLINK';
if(current===3)key=frame%2?'SPEAK_A':'SPEAK_B';document.getElementById('pet').src=images[key]},320);show(0);
</script>'''.replace('IMAGES_PLACEHOLDER', json.dumps(embedded)), encoding='utf-8')
    manifest = {'upstream': 'https://github.com/YunYueSama/codex-deepseek-pet', 'commit': COMMIT,
                'frame_size': [W, H], 'frames': [n for n, _ in frames],
                'pixel_format': 'RGB565 little-endian', 'image_bytes': W * H * 2 * len(frames),
                'sources': {name: hashlib.sha256((UPSTREAM / name).read_bytes()).hexdigest()
                            for name in ('idle-front.png', 'expressions.png', 'dense-sleep.png', 'LICENSE', 'ASSET_LICENSE.md')}}
    (ASSETS / 'manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    print(json.dumps(manifest, indent=2))


if __name__ == '__main__':
    main()
